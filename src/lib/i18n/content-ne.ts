/**
 * Nepali copy for content that lives in `data.ts`.
 *
 * `data.ts` stays the single source of truth for ids, prices, slugs, filters
 * and English copy. This module only overlays the strings a reader sees, keyed
 * by the same ids, so the two can never drift: a renamed product id makes the
 * overlay miss, and `localize.ts` falls back to the English field rather than
 * rendering an empty card.
 *
 * Nothing here is mutated into `data.ts`. The merge happens at render time in
 * `localize.ts`, which means the English site renders exactly the same objects
 * it always did.
 *
 * Terminology: टोकरी = basket, झोला = bag, जैविक = organic, स्थानीय = local,
 * अफर = offers, सदस्यता = membership, डेलिभरी = delivery. Latin digits are kept
 * for prices, quantities, batch codes and dates so a number never changes
 * meaning between languages.
 */

export interface ProductNe {
  name: string;
  unit: string;
  desc: string;
  badge?: string;
  freshness?: string;
  soldOutNote?: string;
  reviews?: Record<string, { author?: string; locality?: string; body: string }>;
}

export interface DishNe {
  name: string;
  portion: string;
  desc: string;
  prepTime: string;
  portions?: Record<string, { label: string; serves: string }>;
  addons?: Record<string, { label: string }>;
}

export interface BasketNe {
  name: string;
  tag?: string;
  desc: string;
  includes: string[];
}

export interface FarmerNe {
  name: string;
  location: string;
  story: string;
  special: string;
  elevation: string;
  regions: string[];
}

export interface CategoryNe {
  name: string;
  note: string;
}

export interface PolicyNe {
  heading: string;
  body: string;
}

